'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { NEXUS_DWT_VIEWS, NEXUS_DWT_SESSION_MS, NEXUS_DWT_PREPARE_IDLE_MS, nexusDwtDeadline } = require('../camera-one-tap-timeout.js');
assert.equal(Object.keys(NEXUS_DWT_VIEWS).length, 3);
assert.equal(NEXUS_DWT_SESSION_MS, 9000);
assert.equal(NEXUS_DWT_PREPARE_IDLE_MS, 20000);
assert.ok(Object.values(NEXUS_DWT_VIEWS).every(x => x.url.startsWith('https://iframe.dacast.com/live/')));
assert.equal(nexusDwtDeadline(120, NEXUS_DWT_SESSION_MS), 9120);
assert.equal(nexusDwtDeadline(0, NEXUS_DWT_SESSION_MS), 9000);
assert.throws(() => nexusDwtDeadline(NaN, 9000), TypeError);
assert.throws(() => nexusDwtDeadline(0, 0), TypeError);
const dir = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(dir, 'camera-one-tap-timeout.html'), 'utf8');
const js = fs.readFileSync(path.join(dir, 'camera-one-tap-timeout.js'), 'utf8');
assert.match(html, /id="cameraPill"/);
assert.match(html, /scale\(6\)/);
assert.match(html, /width:480px;height:270px/);
assert.match(html, /id="resume"/);
assert.match(html, /id="expiredPanel"/);
assert.match(html, /<script src="\.\/camera-one-tap-timeout\.js\?v=1" defer><\/script>/);
assert.match(js, /frame\.removeAttribute\('src'\)/);
assert.match(js, /frame\.src = 'about:blank'/);
assert.match(js, /frame\.remove\(\)/);
assert.match(js, /document\.addEventListener\('visibilitychange'/);
assert.match(js, /window\.addEventListener\('pagehide'/);
assert.match(js, /startBoundedSession\('first', source\)/);
assert.match(js, /startBoundedSession\('resume', 'Resume button click; no playback assumption'\)/);
assert.doesNotMatch(js, /dispatchEvent|new MouseEvent|new PointerEvent|postMessage\(/);
assert.doesNotMatch(html, /<iframe[^>]+src=/);
console.log('Cropped Play + 9s resume diagnostic smoke and lifecycle tests passed.');

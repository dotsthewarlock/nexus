'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {RESUME_CAMERAS,RESUME_VARIANTS,RESUME_SESSION_MS,RESUME_STANDBY_MS,RESUME_INITIAL_IDLE_MS,resumeDeadline,resumePolicy}=require('../camera-resume-candidates.js');
assert.equal(RESUME_SESSION_MS,9000);
assert.equal(RESUME_STANDBY_MS,15000);
assert.equal(RESUME_INITIAL_IDLE_MS,20000);
assert.equal(resumeDeadline(2100),11100);
assert.throws(()=>resumeDeadline(Infinity),TypeError);
assert.equal(Object.keys(RESUME_CAMERAS).length,3);
assert.equal(Object.keys(RESUME_VARIANTS).length,6);
assert.ok(Object.values(RESUME_CAMERAS).every(v=>v.url.startsWith('https://iframe.dacast.com/live/')));
assert.equal(resumePolicy('pill6').zoom,6);
assert.equal(resumePolicy('round6').shape,'round');
assert.equal(resumePolicy('pill4').zoom,4);
assert.equal(resumePolicy('native6').shape,'native');
assert.equal(resumePolicy('full').shape,'full');
assert.equal(resumePolicy('control').prewarm,false);
assert.throws(()=>resumePolicy('unregistered'),TypeError);
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'camera-resume-candidates.html'),'utf8');
const js=fs.readFileSync(path.join(root,'camera-resume-candidates.js'),'utf8');
for(const id of ['main','camera','candidate','prewarm','handoff','launcherPill','resumeTarget','playerLayer','resumeFace','modalShade','closeModal','controlResume','rearm','history','copy','outcome'])
 assert.match(html,new RegExp('id="'+id+'"'));
assert.match(html,/scale\(var\(--crop-zoom,6\)\)/);
assert.match(html,/width:480px;height:270px/);
assert.match(html,/<script src="\.\/camera-resume-candidates\.js\?v=1" defer><\/script>/);
assert.match(js,/frame\.removeAttribute\('src'\)/);
assert.match(js,/frame\.src='about:blank'/);
assert.match(js,/frame\.remove\(\)/);
assert.match(js,/generation\+\+/);
assert.match(js,/if\(document\.hidden\)closeAll\('Page hidden \/ visibilitychange'\)/);
assert.match(js,/window\.addEventListener\('pagehide'/);
assert.match(js,/function armResume\(/);
assert.match(js,/state='resume-ready'/);
assert.match(js,/function controlResume\(/);
assert.doesNotMatch(js,/dispatchEvent|new MouseEvent|new PointerEvent|postMessage\(/);
assert.doesNotMatch(html,/<iframe[^>]*\bsrc=/);
console.log('In-modal Resume variants: policy and lifecycle static tests passed.');
